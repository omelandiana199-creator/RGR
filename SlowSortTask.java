public class SlowSortTask {

    private SlowSortTask() {}

    
    public static void slowSort(double[] a, int i, int j) {
        if (i >= j) {
            return;
        }

        // Знаходимо середину поточного відрізка.
        int m = i + (j - i) / 2;

        // Рекурсивно відшукуємо максимум у лівій половині відрізка
        // і виштовхуємо його в кінець цієї ж лівої половини (на позицію m).
        slowSort(a, i, m);

        // Рекурсивно відшукуємо максимум у правій половині відрізка
        // і виштовхуємо його в кінець правої половини (на позицію j).
        slowSort(a, m + 1, j);

        // Порівнюємо максимуми обох половин (елементи на позиціях m та j).
        // Якщо максимум лівої половини більший за максимум правої,
        if (a[m] > a[j]) {
            // міняємо їх місцями, щоб абсолютний максимум всього поточного
            // відрізка гарантовано опинився на найостаннішій позиції (j).
            double temp = a[m];
            a[m] = a[j];
            a[j] = temp;
        }


        slowSort(a, i, j - 1);// Рекурсивно сортуємо решту масиву (до j - 1).
    }
}
