public class SlowSortTask {

    private SlowSortTask() {}

    /**
     * Публічний метод для запуску сортування.
     * @param a масив чисел типу double для сортування
     */
    public static void sort(double[] a) {
        // Перевірка на null або порожній масив
        if (a == null || a.length <= 1) {
            return;
        }
        slowSort(a, 0, a.length - 1);
    }

    /**
     * Рекурсивна реалізація SlowSort.
     * @param a масив, який сортується
     * @param i початковий індекс області сортування
     * @param j кінцевий індекс області сортування
     */
    public static void slowSort(double[] a, int i, int j) {
      // Базовий випадок рекурсії: якщо в підмасиві 1 або 0 елементів
        if (i >= j) {
            return;
        }

        // Знаходимо середній індекс для поділу масиву навпіл
        int m = i + (j - i) / 2;

       /* 
         *  Рекурсивно викликаємо сортування для обох частин.
         * Виштовхуємо локальні максимуми в кінець кожної частини 
         * (в індекси m та j відповідно).
         */
        slowSort(a, i, m);
        slowSort(a, m + 1, j);

        /* 
         * Порівнюємо елементи на кінцях підмасивів.
         * Якщо елемент посередині (a[m]) більший за останній (a[j]), 
         * міняємо їх місцями. Тепер в a[j] гарантовано лежить максимум для всього діапазону [i...j].
         */
        if (a[m] > a[j]) {
            double temp = a[m];
            a[m] = a[j];
            a[j] = temp;
        }

        /* 
         * Тепер, коли ми знайшли глобальний максимум для поточної ділянки
         * і поставили його в самий кінець (індекс j), ми викликаємо slowSort 
         * для всього масиву за винятком цього останнього елемента.
         */
        slowSort(a, i, j - 1);
    }
}
